class axi2apb_coverage extends uvm_component;

  `uvm_component_utils(axi2apb_coverage)


  // ==========================================================================
  // ANALYSIS IMPORTS
  // ==========================================================================

  uvm_analysis_imp_axi #(
    axi_master_item,
    axi2apb_coverage
  ) axi_imp;


  uvm_analysis_imp_apb #(
    apb_slave_item,
    axi2apb_coverage
  ) apb_imp;


  // ==========================================================================
  // LOCAL TRANSACTION HANDLES
  // ==========================================================================

  axi_master_item axi_tr;

  apb_slave_item apb_tr;


  // ==========================================================================
  // AXI COVERGROUP
  // ==========================================================================

  covergroup axi_cg;

    option.per_instance = 1;


    // ------------------------------------------------------------------------
    // AXI READ / WRITE
    // ------------------------------------------------------------------------

    cp_axi_operation : coverpoint axi_tr.write {

      bins read  = {1'b0};

      bins write = {1'b1};

    }


    // ------------------------------------------------------------------------
    // ADDRESS REGIONS
    // ------------------------------------------------------------------------

    cp_axi_address : coverpoint axi_tr.addr {

      bins low =
        {[32'h0000_0000 : 32'h0000_3FFC]};

      bins middle =
        {[32'h0000_4000 : 32'h0000_BFFC]};

      bins high =
        {[32'h0000_C000 : 32'h0000_FFFC]};

    }


    // ------------------------------------------------------------------------
    // WORD ALIGNMENT
    // ------------------------------------------------------------------------

    cp_axi_alignment : coverpoint axi_tr.addr[1:0] {

      bins aligned =
        {2'b00};

      ignore_bins unsupported_alignment = {
        2'b01,
        2'b10,
        2'b11
      };

    }


    // ------------------------------------------------------------------------
    // AXI RESPONSE
    //
    // Supplied RTL generates OKAY.
    //
    // EXOKAY, SLVERR and DECERR are not generated by this supplied RTL
    // for the currently verified conversion path.
    // ------------------------------------------------------------------------

    cp_axi_response : coverpoint axi_tr.resp {

      bins okay =
        {2'b00};

      ignore_bins unsupported_response = {
        2'b01,
        2'b10,
        2'b11
      };

    }


    // ------------------------------------------------------------------------
    // AXI ID
    // ------------------------------------------------------------------------

    cp_axi_id : coverpoint axi_tr.id {

      bins low =
        {[16'h0000 : 16'h3FFF]};

      bins middle =
        {[16'h4000 : 16'hBFFF]};

      bins high =
        {[16'hC000 : 16'hFFFF]};

    }


    // ------------------------------------------------------------------------
    // AXI USER
    // ------------------------------------------------------------------------

    cp_axi_user : coverpoint axi_tr.user {

      bins low =
        {[10'h000 : 10'h0FF]};

      bins middle =
        {[10'h100 : 10'h2FF]};

      bins high =
        {[10'h300 : 10'h3FF]};

    }


    // ------------------------------------------------------------------------
    // AXI OPERATION x ADDRESS
    //
    // We want read/write accesses in low/middle/high regions.
    // ------------------------------------------------------------------------

    cross_axi_operation_address :
      cross cp_axi_operation,
            cp_axi_address;


    // ------------------------------------------------------------------------
    // AXI OPERATION x RESPONSE
    //
    // Current supplied RTL should cover:
    //
    // READ  x OKAY
    // WRITE x OKAY
    // ------------------------------------------------------------------------

    cross_axi_operation_response :
      cross cp_axi_operation,
            cp_axi_response;


    // ------------------------------------------------------------------------
    // AXI OPERATION x ID REGION
    // ------------------------------------------------------------------------

    cross_axi_operation_id :
      cross cp_axi_operation,
            cp_axi_id;


    // ------------------------------------------------------------------------
    // AXI OPERATION x USER REGION
    // ------------------------------------------------------------------------

    cross_axi_operation_user :
      cross cp_axi_operation,
            cp_axi_user;


  endgroup



  // ==========================================================================
  // APB COVERGROUP
  // ==========================================================================

  covergroup apb_cg;

    option.per_instance = 1;


    // ------------------------------------------------------------------------
    // APB READ / WRITE
    // ------------------------------------------------------------------------

    cp_apb_operation : coverpoint apb_tr.write {

      bins read =
        {1'b0};

      bins write =
        {1'b1};

    }


    // ------------------------------------------------------------------------
    // APB ADDRESS REGIONS
    // ------------------------------------------------------------------------

    cp_apb_address : coverpoint apb_tr.addr {

      bins low =
        {[32'h0000_0000 : 32'h0000_3FFC]};

      bins middle =
        {[32'h0000_4000 : 32'h0000_BFFC]};

      bins high =
        {[32'h0000_C000 : 32'h0000_FFFC]};

    }


    // ------------------------------------------------------------------------
    // APB ADDRESS ALIGNMENT
    // ------------------------------------------------------------------------

    cp_apb_alignment : coverpoint apb_tr.addr[1:0] {

      bins aligned =
        {2'b00};

      ignore_bins unsupported_alignment = {
        2'b01,
        2'b10,
        2'b11
      };

    }


    // ------------------------------------------------------------------------
    // APB PSLVERR
    //
    // BOTH are real verification goals:
    //
    // 0 -> normal APB completion
    // 1 -> APB error stimulus
    // ------------------------------------------------------------------------

    cp_apb_error : coverpoint apb_tr.pslverr {

      bins no_error =
        {1'b0};

      bins error =
        {1'b1};

    }


    // ------------------------------------------------------------------------
    // READ/WRITE x ADDRESS
    // ------------------------------------------------------------------------

    cross_apb_operation_address :
      cross cp_apb_operation,
            cp_apb_address;


    // ------------------------------------------------------------------------
    // READ/WRITE x PSLVERR
    //
    // Goals:
    //
    // WRITE + no_error
    // WRITE + error
    // READ  + no_error
    // READ  + error
    // ------------------------------------------------------------------------

    cross_apb_operation_error :
      cross cp_apb_operation,
            cp_apb_error;


  endgroup



  // ==========================================================================
  // CONSTRUCTOR
  // ==========================================================================

  function new(
    string name = "axi2apb_coverage",
    uvm_component parent = null
  );

    super.new(name, parent);

    axi_cg = new();

    apb_cg = new();

  endfunction


  // ==========================================================================
  // BUILD PHASE
  // ==========================================================================

  virtual function void build_phase(
    uvm_phase phase
  );

    super.build_phase(phase);


    `uvm_info(
      "COV",
      "axi2apb_coverage build_phase executed",
      UVM_LOW
    )


    axi_imp = new(
      "axi_imp",
      this
    );


    apb_imp = new(
      "apb_imp",
      this
    );

  endfunction


  // ==========================================================================
  // AXI COVERAGE CALLBACK
  // ==========================================================================

  function void write_axi(
    axi_master_item t
  );

    axi_tr = t;


    axi_cg.sample();


    `uvm_info(
      "COV_AXI",
      $sformatf(
        "Sampled AXI: %s addr=0x%08h id=0x%04h user=0x%03h resp=%02b",
        t.write ? "WRITE" : "READ",
        t.addr,
        t.id,
        t.user,
        t.resp
      ),
      UVM_HIGH
    )

  endfunction


  // ==========================================================================
  // APB COVERAGE CALLBACK
  // ==========================================================================

  function void write_apb(
    apb_slave_item t
  );

    apb_tr = t;


    apb_cg.sample();


    `uvm_info(
      "COV_APB",
      $sformatf(
        "Sampled APB: %s addr=0x%08h PSLVERR=%0b",
        t.write ? "WRITE" : "READ",
        t.addr,
        t.pslverr
      ),
      UVM_HIGH
    )

  endfunction


  // ==========================================================================
  // REPORT PHASE
  // ==========================================================================

  virtual function void report_phase(
    uvm_phase phase
  );

    real axi_cov;
    real apb_cov;


    super.report_phase(phase);


    axi_cov =
      axi_cg.get_inst_coverage();


    apb_cov =
      apb_cg.get_inst_coverage();


    `uvm_info(
      "COV",
      $sformatf(
        "AXI Functional Coverage = %0.2f%%",
        axi_cov
      ),
      UVM_LOW
    )


    `uvm_info(
      "COV",
      $sformatf(
        "APB Functional Coverage = %0.2f%%",
        apb_cov
      ),
      UVM_LOW
    )


    `uvm_info(
      "COV",
      "axi2apb_coverage report_phase executed",
      UVM_LOW
    )

  endfunction


endclass
